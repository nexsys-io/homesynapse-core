// Every command outcome + every run status, one automation, as a run list you can click through.
function buildAllOutcomes(): MockDataset {
  const A = { automationId: 'auto_demo', automationName: 'Demo automation' };
  const specs: { id: string; outcome: ActionOutcome; status: RunStatus; reason?: string | null; min: number }[] = [
    { id: 'run_oc_confirmed', outcome: 'CONFIRMED', status: 'COMPLETED', min: 2 },
    { id: 'run_oc_dispatched', outcome: 'DISPATCHED', status: 'COMPLETED', reason: 'Command sent; awaiting confirmation', min: 4 },
    { id: 'run_oc_unconfirmed', outcome: 'UNCONFIRMED', status: 'COMPLETED', reason: 'Action sent; device did not confirm within 5s', min: 9 },
    { id: 'run_oc_failed', outcome: 'FAILED', status: 'FAILED', reason: 'Device unreachable', min: 22 },
    { id: 'run_oc_skipped', outcome: 'SKIPPED', status: 'SKIPPED', reason: 'Condition not met: before sunset', min: 40 },
    { id: 'run_oc_cancelled', outcome: 'SKIPPED', status: 'CANCELLED', reason: 'Superseded by a newer run', min: 70 },
    { id: 'run_oc_interrupted', outcome: 'FAILED', status: 'INTERRUPTED', reason: 'System restarted mid-run', min: 130 },
  ];
  const runs = specs.map((s) => makeRun(s.id, { ...A, status: s.status, terminalReason: s.reason ?? null, minAgo: s.min }));
  const causalChains: Record<string, CausalChain> = {};
  for (const s of specs) {
    causalChains[s.id] = makeChain(s.id, {
      ...A,
      outcome: s.outcome,
      status: s.status,
      conditionResult: s.status !== 'SKIPPED',
      terminalReason: s.reason ?? null,
      minAgo: s.min,
    });
  }
  return {
    ...defaultDataset,
    automations: [makeAutomation('auto_demo', 'Demo automation', { lastRunId: 'run_oc_confirmed' })],
    runs,
    causalChains,
    nonFiring: { auto_demo: makeNonFiring('auto_demo', 'NEVER_TRIGGERED', { automationName: 'Demo automation' }) },
  };
}

// A parent → child cascade: one run triggers another; the child links back to its cause.
function buildCascade(): MockDataset {
  const parent = makeChain('run_casc_parent', {
    automationId: 'auto_sunset',
    automationName: 'Sunset Scene',
    triggerId: 'sys_sun',
    targetId: 'ent_livingroom_lamp',
    minAgo: 3,
  });
  parent.trigger = { type: 'time', subjectRef: { type: 'SYSTEM', id: 'sys_sun' }, matchedAt: iso(3), firingValue: 'sun set' };
  const child = makeChain('run_casc_child', {
    automationId: 'auto_evening_hallway',
    automationName: 'Evening Hallway Light',
    parentRunId: 'run_casc_parent',
    depth: 1,
    minAgo: 3,
  });
  return {
    ...defaultDataset,
    automations: [
      makeAutomation('auto_sunset', 'Sunset Scene', { lastRunId: 'run_casc_parent' }),
      makeAutomation('auto_evening_hallway', 'Evening Hallway Light', { lastRunId: 'run_casc_child' }),
    ],
    runs: [
      makeRun('run_casc_child', { automationId: 'auto_evening_hallway', automationName: 'Evening Hallway Light', minAgo: 3 }),
      makeRun('run_casc_parent', { automationId: 'auto_sunset', automationName: 'Sunset Scene', minAgo: 3 }),
    ],
    causalChains: { run_casc_parent: parent, run_casc_child: child },
  };
}

// All four "why didn't it fire?" verdicts, one automation each.
function buildAllVerdicts(): MockDataset {
  const defs: { id: string; name: string; verdict: NonFiringVerdict }[] = [
    { id: 'auto_v_condition', name: 'Front Door Welcome', verdict: 'CONDITION_NOT_MET' },
    { id: 'auto_v_never', name: 'Evening Hallway Light', verdict: 'NEVER_TRIGGERED' },
    { id: 'auto_v_acted', name: 'Bedtime Lights Off', verdict: 'ACTED_BUT_UNCONFIRMED' },
    { id: 'auto_v_disabled', name: 'Bedroom Night Light', verdict: 'DISABLED' },
  ];
  const nonFiring: Record<string, NonFiringExplanation> = {};
  for (const d of defs) nonFiring[d.id] = makeNonFiring(d.id, d.verdict, { automationName: d.name });
  return {
    ...defaultDataset,
    automations: defs.map((d) => makeAutomation(d.id, d.name, { enabled: d.verdict !== 'DISABLED' })),
    nonFiring,
  };
}

// Every event origin, including the honest UNKNOWN (never a silent blank).
function buildAllOrigins(): MockDataset {
  const origins: Origin[] = ['AUTOMATION', 'DEVICE', 'USER', 'EXTERNAL', 'UNKNOWN'];
  return {
    ...defaultDataset,
    events: origins.map((o, i) => makeEvent(`evt_origin_${i}`, o, { occurredAt: iso(i + 1) })),
  };
}

// Hundreds of rows — the input that forces list virtualization (T2.3) and stresses render-at-scale.
function buildLarge(): MockDataset {
  const STATUSES: RunStatus[] = ['COMPLETED', 'FAILED', 'SKIPPED', 'CANCELLED', 'INTERRUPTED'];
  const OUTCOMES: ActionOutcome[] = ['CONFIRMED', 'DISPATCHED', 'UNCONFIRMED', 'FAILED', 'SKIPPED'];
  const ORIGINS: Origin[] = ['AUTOMATION', 'DEVICE', 'USER', 'EXTERNAL', 'UNKNOWN'];
  const runs: RunSummary[] = [];
  const causalChains: Record<string, CausalChain> = {};
  for (let i = 0; i < 300; i++) {
    const id = `run_lg_${String(i).padStart(4, '0')}`;
    const status = STATUSES[i % STATUSES.length]!;
    const outcome = OUTCOMES[i % OUTCOMES.length]!;
    runs.push(makeRun(id, { status, minAgo: i * 7 + 2, terminalReason: status === 'COMPLETED' ? null : `${status.toLowerCase()} (#${i})` }));
    causalChains[id] = makeChain(id, { outcome, status, minAgo: i * 7 + 2 });
  }
  const events: EventSummary[] = [];
  for (let i = 0; i < 500; i++) {
    events.push(makeEvent(`evt_lg_${String(i).padStart(4, '0')}`, ORIGINS[i % ORIGINS.length]!, { occurredAt: iso(i + 1) }));
  }
  return { ...defaultDataset, automations: [makeAutomation('auto_demo', 'Demo automation')], runs, causalChains, events };
}

