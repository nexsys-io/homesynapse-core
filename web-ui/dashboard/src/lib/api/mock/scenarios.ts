/*
 * HomeSynapse — Mock SCENARIOS (T1.2, the pre-hardware sprint keystone).
 * ---------------------------------------------------------------------------
 * A scenario system that can produce EVERY condition the FROZEN v1.1 contract allows, on
 * demand — so the mock demo is complete now, FE-4 can verify every state on realistic data,
 * and live-integration (FE-1) meets no shape it hasn't already faced. Every dataset is shaped
 * by the same contract types the real transport returns; contract.test.ts validates them.
 *
 * Two orthogonal dimensions (see mockState.ts): a DATA scenario (the story the data tells) and
 * a TRANSPORT condition (replaying / offline / slow / 401 / 403 / etag). This file owns the data.
 *
 * Bundle note: variant datasets are built lazily (`build()`), and large lists are GENERATED by
 * code (not materialized literals), so the static footprint stays small — mock ships in the
 * demo/website-embed builds (sprint §T1.2), and we keep the 100 KB budget honest.
 */
